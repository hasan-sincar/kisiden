String getTranslatedText(Map<String, dynamic>? data, String key) {
  if (data == null) return '';
  String lang = appLocale.value.languageCode;
  if (lang != 'tr') {
    String? translated = data['${key}_$lang'];
    if (translated != null && translated.toString().trim().isNotEmpty) {
      return translated;
    }
  }
  return data[key] ?? '';
}

List<String> getTranslatedList(Map<String, dynamic>? data, String key) {
  if (data == null) return [];
  String lang = appLocale.value.languageCode;
  if (lang != 'tr') {
    List<dynamic>? translated = data['${key}_$lang'];
    if (translated != null && translated.isNotEmpty) {
      return List<String>.from(translated);
    }
  }
  List<dynamic>? baseList = data[key];
  if (baseList != null) {
    return List<String>.from(baseList);
  }
  return [];
}
