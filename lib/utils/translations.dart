// Metinleri hızlıca çeviren yardımcı fonksiyon
String tr(String key) {
  String lang = appLocale.value.languageCode;
  Map<String, String>? translations = _dict[lang];

  // Eğer seçili dilde kelime yoksa veya dil bulunamadıysa Türkçe (fallback) kullan
  if (translations == null || !translations.containsKey(key)) {
    translations = _dict['tr'];
  }

  return translations?[key] ??
      key; // Kelime hiç yoksa anahtarın (key) kendisini göster
}

String translateNotification(String key, String lang, [List<String>? args]) {
  Map<String, String>? translations = _dict[lang];
  if (translations == null || !translations.containsKey(key)) {
    translations = _dict['tr'];
  }
  String text = translations?[key] ?? key;

  if (args != null) {
    for (int i = 0; i < args.length; i++) {
      String arg = args[i];
      if (translations != null && translations.containsKey(arg)) {
        arg = translations[arg]!;
      } else if (_dict['tr']!.containsKey(arg)) {
        arg = _dict['tr']![arg]!;
      }
      text = text.replaceFirst('%s', arg);
    }
  }
  return text;
}

